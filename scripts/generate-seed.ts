/**
 * Generates supabase/seed.sql from the TypeScript seed content in src/content.
 * Run with: npm run seed:generate
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  BOARD_TERM,
  FEATURE_FLAG_DESCRIPTIONS,
  board,
  callForPapers,
  categories,
  featureFlags,
  settings,
} from "../src/content/journal";
import { pages, policies } from "../src/content/pages";
import { sampleInPress, sampleIssues, type SampleArticle } from "../src/content/samples";
import { stableUuid } from "../src/lib/ids";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const out: string[] = [
  "-- GENERATED by scripts/generate-seed.ts from src/content. Do not edit by hand.",
  "-- Seeds categories, the editorial board, pages and policies, settings, flags,",
  "-- the first Call for Papers, and SAMPLE volumes (remove with npm run samples:delete).",
  "",
  "begin;",
  "",
];

// Settings: one row per top-level key so each can be edited and versioned.
out.push("-- Site settings");
for (const [key, value] of Object.entries(settings)) {
  out.push(
    `insert into public.site_settings (key, value, is_public) values (${q(key)}, ${json(value)}, true) on conflict (key) do nothing;`,
  );
}
out.push("");

out.push("-- Feature flags");
for (const [key, enabled] of Object.entries(featureFlags)) {
  out.push(
    `insert into public.feature_flags (key, enabled, description) values (${q(key)}, ${enabled}, ${q(
      FEATURE_FLAG_DESCRIPTIONS[key as keyof typeof featureFlags],
    )}) on conflict (key) do nothing;`,
  );
}
out.push("");

out.push("-- Categories");
for (const c of categories) {
  out.push(
    `insert into public.categories (id, name, slug, short_description, description, thread_color, sort_order) values (${[
      c.id,
      c.name,
      c.slug,
      c.shortDescription,
      c.description,
      c.threadColor,
      c.sortOrder,
    ]
      .map(q)
      .join(", ")}) on conflict (id) do nothing;`,
  );
}
out.push("");

out.push("-- Editorial board (terms stored; shown only when showBoardTerms is on)");
board.forEach((m, i) => {
  out.push(
    `insert into public.editorial_board_members (id, "group", name, affiliation, term_start, term_end, sort_order) values (${[
      stableUuid(`board:${m.name}`),
      m.group,
      m.name,
      m.affiliation,
      BOARD_TERM.start,
      BOARD_TERM.end,
      i,
    ]
      .map(q)
      .join(", ")}) on conflict (id) do nothing;`,
  );
});
out.push("");

out.push("-- Pages and policies");
for (const p of [...pages, ...policies]) {
  out.push(
    `insert into public.pages (id, kind, slug, title, summary, body_html, sort_order) values (${[
      stableUuid(`${p.kind}:${p.slug}`),
      p.kind,
      p.slug,
      p.title,
      p.summary,
      p.bodyHtml,
      p.sortOrder,
    ]
      .map(q)
      .join(", ")}) on conflict (kind, slug) do nothing;`,
  );
}
out.push("");

out.push("-- Call for Papers (one active)");
out.push(
  `insert into public.call_for_papers (id, title, target_label, summary_html, banner_text, submission_deadline, review_period, publication_month, is_active) values (${[
    stableUuid("cfp:1"),
    callForPapers.title,
    callForPapers.targetLabel,
    callForPapers.summaryHtml,
    callForPapers.bannerText,
    callForPapers.submissionDeadline,
    callForPapers.reviewPeriod,
    callForPapers.publicationMonth,
    true,
  ]
    .map(q)
    .join(", ")}) on conflict (id) do nothing;`,
);
out.push("");

// ---------------------------------------------------------------------------
// SAMPLE content
// ---------------------------------------------------------------------------

out.push("-- SAMPLE volumes, issues and articles");
const catId = new Map(categories.map((c) => [c.slug, c.id]));
const volumes = new Map<number, number>();
for (const i of sampleIssues) volumes.set(i.volume, i.year);
for (const [number, year] of volumes) {
  out.push(
    `insert into public.volumes (id, number, year, is_sample) values (${q(stableUuid(`volume:${number}`))}, ${number}, ${year}, true) on conflict (number) do nothing;`,
  );
}

function article(
  a: SampleArticle,
  issueId: string | null,
  status: "published" | "in_press",
  dateIso: string,
  sortOrder: number,
) {
  const id = stableUuid(`article:${a.slug}`);
  const published = new Date(dateIso);
  const received = new Date(published.getTime() - 120 * 864e5).toISOString().slice(0, 10);
  const accepted = new Date(published.getTime() - 40 * 864e5).toISOString().slice(0, 10);
  out.push(
    `insert into public.articles (id, issue_id, category_id, type, title, slug, abstract, keywords, first_page, last_page, citation_style, received_at, accepted_at, online_at, published_at, status, sort_order, view_count, download_count, body_html, is_sample) values (${[
      id,
      issueId,
      catId.get(a.category) ?? null,
      a.type,
      a.title,
      a.slug,
      a.abstract,
      a.keywords,
      a.pages?.[0] ?? null,
      a.pages?.[1] ?? null,
      a.citationStyle,
      received,
      accepted,
      dateIso,
      status === "published" ? dateIso : null,
      status,
      sortOrder,
      a.views,
      a.downloads,
      a.bodyHtml ?? null,
      true,
    ]
      .map(q)
      .join(", ")}) on conflict (id) do nothing;`,
  );
  a.authors.forEach((au, pos) => {
    out.push(
      `insert into public.article_authors (article_id, position, name, affiliation, orcid, is_corresponding) values (${[
        id,
        pos + 1,
        au.name,
        au.affiliation,
        au.orcid ?? null,
        Boolean(au.corresponding),
      ]
        .map(q)
        .join(", ")});`,
    );
  });
  if (a.book) {
    out.push(
      `insert into public.book_reviews (article_id, book_title, book_author, publisher, year, isbn, pages) values (${[
        id,
        a.book.title,
        a.book.author,
        a.book.publisher,
        a.book.year,
        a.book.isbn,
        a.book.pages,
      ]
        .map(q)
        .join(", ")}) on conflict (article_id) do nothing;`,
    );
  }
}

for (const issue of sampleIssues) {
  const issueId = stableUuid(`issue:${issue.volume}:${issue.number}`);
  out.push(
    `insert into public.issues (id, volume_id, number, month, editorial, status, published_at, is_sample) values (${[
      issueId,
      stableUuid(`volume:${issue.volume}`),
      issue.number,
      issue.month,
      issue.editorial,
      "published",
      issue.publishedAt,
      true,
    ]
      .map(q)
      .join(", ")}) on conflict (id) do nothing;`,
  );
  issue.articles.forEach((a, i) => article(a, issueId, "published", issue.publishedAt, i + 1));
}
sampleInPress.forEach((a, i) => article(a, null, "in_press", a.onlineAt, i + 1));

out.push("", "commit;", "");

const target = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(target, out.join("\n"));
console.log(`Wrote ${target} (${out.length} lines)`);
